import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { serveDist } from '../helpers/browser-harness.mjs';
import { masteryCourseFiles } from '../fixtures/mastery/course.mjs';

for (const width of [1440, 390]) test(`external work and pre-feedback defense survive reload at ${width}px`, async () => {
  const files = masteryCourseFiles(), course = JSON.parse(files['course.json']);
  course.state = { enabled: true }; files['course.json'] = JSON.stringify(course);
  const server = await serveDist('.'), browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width, height: 950 } });
    page.setDefaultTimeout(10000);
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.route('**/courses/demo.json', route => route.fulfill({ json: files }));
    const visit = async id => {
      await page.goto(`${server.origin}/#/demo/activity/${id}`);
      await page.getByRole('button', { name: 'Save draft', exact: true }).waitFor();
    };
    await visit('lab');
    assert.equal(await page.getByRole('link', { name: 'Open public package' }).getAttribute('href'), 'https://example.invalid/ledger-v1.zip');
    await page.getByLabel('Code, report or explanation', { exact: true }).fill('Fixed cost calculation');
    await page.getByRole('button', { name: 'Add artifact reference' }).click();
    await page.getByLabel('HTTPS file URL').fill('https://example.invalid/work.txt');
    await page.getByLabel('Artifact SHA-256', { exact: true }).fill('a'.repeat(64));
    await page.getByLabel('File size in bytes').fill('120');
    await page.getByLabel('ai', { exact: true }).check();
    await page.getByLabel('Active minutes').fill('4');
    await page.getByLabel('Environment used').fill('Local Python');
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    await page.getByText('Draft saved with assistance and reported time.', { exact: true }).waitFor();
    await page.reload();
    await page.getByLabel('Code, report or explanation', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('Code, report or explanation', { exact: true }).inputValue(), 'Fixed cost calculation');
    assert.equal(await page.getByLabel('Active minutes').inputValue(), '4');
    assert.equal(await page.getByLabel('ai', { exact: true }).isChecked(), true);
    await page.getByRole('button', { name: 'Commit submission', exact: true }).click();
    await page.getByText(/Saved attempts: 1/).waitFor();
    assert.equal(await page.getByLabel('Result JSON', { exact: true }).count(), 0);
    await page.locator('.activity-submission details summary').first().click();
    const request = JSON.parse(await page.getByLabel('Submission envelope for external review').inputValue());
    await page.getByLabel('Code, report or explanation', { exact: true }).fill('Fixed cost calculation');
    await page.getByRole('button', { name: 'Add artifact reference' }).click();
    await page.getByLabel('HTTPS file URL').fill('https://example.invalid/work.txt');
    await page.getByLabel('Artifact SHA-256', { exact: true }).fill('a'.repeat(64));
    await page.getByLabel('File size in bytes').fill('120');
    await page.getByRole('button', { name: 'Commit submission', exact: true }).click();
    await page.getByText(/This input is already committed/).waitFor();

    await page.getByRole('link', { name: 'Continue to written defense' }).click();
    await page.locator('[data-activity-id="defense"]').waitFor();
    await page.getByRole('button', { name: 'Save draft', exact: true }).waitFor();
    await page.getByLabel('Code, report or explanation', { exact: true }).fill('The calculation rounds each request before summing.');
    await page.getByLabel('Environment used').fill('Reviewer discussion');
    await page.getByRole('button', { name: 'Commit submission', exact: true }).click();
    await page.getByLabel('Reviewer-selected fresh prompt').waitFor();
    assert.equal(await page.getByLabel('Result JSON', { exact: true }).count(), 0);
    await page.getByLabel('Reviewer name or ID').fill('Claimed reviewer');
    await page.getByLabel('Reviewer-selected fresh prompt').fill('How would zero requests change the result?');
    await page.getByLabel('Follow-up answer', { exact: true }).fill('The sum is zero.');
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    await page.getByText(/Draft saved/).waitFor();
    await page.reload();
    await page.getByLabel('Follow-up answer', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('Follow-up answer', { exact: true }).inputValue(), 'The sum is zero.');
    await page.getByRole('button', { name: 'Commit follow-up before feedback' }).click();
    await page.getByText(/Saved attempts: 2/).waitFor();
    await page.getByLabel('Code, report or explanation', { exact: true }).fill('The calculation rounds each request before summing.');
    await page.getByRole('button', { name: 'Commit submission', exact: true }).click();
    await page.getByText(/This input is already committed/).waitFor();
    await page.getByRole('button', { name: 'Start a fresh draft' }).click();
    await page.getByText('Draft cleared. Committed work is retained.', { exact: true }).waitFor();
    await page.reload();
    await page.getByText(/Saved attempts: 2/).waitFor();
    assert.equal(await page.getByLabel('Code, report or explanation', { exact: true }).inputValue(), '');
    await visit('lab');
    await page.getByLabel('Result JSON', { exact: true }).waitFor();
    const { input, ...binding } = request;
    const result = { ...binding, status: 'complete', criteria: [{ root: 'simple', facet: 'explain', skill: 'a', anchor: 3, criterion: 'correct', outcome: 'pass' }],
      provenance: { kind: 'reviewer-claim', reviewerId: 'human', issuedAt: Date.now() } };
    await page.getByLabel('Result JSON', { exact: true }).fill('{bad json');
    await page.getByRole('button', { name: 'Import provisional result' }).click();
    await page.locator('.activity-submission [role=alert]').waitFor();
    await page.getByLabel('Result JSON', { exact: true }).fill(JSON.stringify({ ...result, trust: 'verified' }));
    await page.getByRole('button', { name: 'Import provisional result' }).click();
    await page.getByText(/unknown key trust/).waitFor();
    await page.getByLabel('Result JSON', { exact: true }).fill(JSON.stringify(result));
    await page.getByRole('button', { name: 'Import provisional result' }).click();
    await page.getByRole('button', { name: 'Show saved rubric feedback' }).waitFor();
    assert.equal(await page.getByText(/Provisional feedback \(/).count(), 0);
    await page.getByRole('button', { name: 'Show saved rubric feedback' }).focus();
    await page.keyboard.press('Enter');
    await page.getByText(/Provisional feedback \(reviewer-claim\)/).waitFor();
    await page.reload();
    await page.getByText(/Provisional feedback \(reviewer-claim\)/).waitFor();
    await page.locator('.activity-submission details summary').first().click();
    await page.getByText(/bytes unavailable here ·/).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: `/tmp/s11-${width}.png`, fullPage: true });
    assert.deepEqual(errors, []);
  } finally { await browser.close(); server.close(); }
});
