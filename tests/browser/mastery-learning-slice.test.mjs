import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { chromium } from 'playwright';
import { serveDist } from '../helpers/browser-harness.mjs';
import { learningSliceFiles } from '../fixtures/mastery/learning-slice.mjs';
import { ledgerPackage } from '../../examples/mastery-cost-ledger/package.mjs';

for (const width of [1440, 390]) test(`runnable ledger lesson, external submission and fresh-browser resume at ${width}px`, async () => {
  const pkg = ledgerPackage(), files = learningSliceFiles(pkg.sha256);
  const server = await serveDist('.'), browser = await chromium.launch();
  try {
    const context = await browser.newContext({ viewport: { width, height: 950 } });
    await context.route('**/courses/demo.json', route => route.fulfill({ json: files }));
    let packageRequests = 0;
    await context.route('https://ledger.invalid/cost-ledger-1.0.0.zip', route => {
      packageRequests++;
      return route.fulfill({ body: Buffer.from(pkg.bytes), contentType: 'application/zip',
        headers: { 'content-disposition': 'attachment; filename="cost-ledger-1.0.0.zip"' } });
    });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', e => errors.push(e.message)); page.setDefaultTimeout(10000);
    const visit = async route => { await page.goto(`${server.origin}/#/demo/${route}`); };
    await visit('s1-1');
    await page.locator('#s1-1 .bhtml').first().waitFor();
    const reading = await page.locator('#s1-1').innerText();
    assert.match(reading, /A ledger lists billable requests/);
    assert.match(reading, /1 \+ 1 = 2 cents/);
    assert.match(reading, /each facet is scored separately/i);
    assert.match(reading, /Missing Python is an environment gap/);
    assert.equal(packageRequests, 0, 'reading/import does not fetch or execute the lab');
    await page.screenshot({ path: `/tmp/s12-reading-${width}.png`, fullPage: true });
    await visit('activity/teach%3As1-1');
    await page.getByRole('button', { name: 'I have read this lesson' }).click();
    await visit('activity/ordinary');
    await page.locator('input[data-numeric-answer]').fill('2');
    await page.getByRole('button', { name: /^Check answer/ }).click();
    await page.locator('.qresult').filter({ hasText: /^Correct$/ }).waitFor();
    await page.reload(); await page.locator('.qresult').filter({ hasText: /^Correct$/ }).waitFor();
    await visit('activity/lab');
    await page.getByRole('button', { name: 'Save draft', exact: true }).waitFor();
    assert.equal(await page.locator('.submission-hash').innerText(), pkg.sha256);
    const download = page.waitForEvent('download');
    await page.getByRole('link', { name: 'Open public package' }).click();
    const downloaded = await download;
    assert.equal(createHash('sha256').update(readFileSync(await downloaded.path())).digest('hex'), pkg.sha256);
    assert.equal(packageRequests, 1);
    await page.getByLabel('Code, report or explanation', { exact: true }).fill('Per-row Decimal rounding fixed; base 2, fresh 5, delayed 3, empty 0.');
    await page.getByLabel('Environment used').fill('CPython 3.14.7; local public checks');
    await page.getByRole('button', { name: 'Save draft', exact: true }).click();
    await page.getByText(/Draft saved with assistance/).waitFor();
    await page.reload(); await page.getByLabel('Code, report or explanation', { exact: true }).waitFor();
    assert.match(await page.getByLabel('Code, report or explanation', { exact: true }).inputValue(), /base 2/);
    await page.getByRole('button', { name: 'Commit submission', exact: true }).click();
    await page.getByText(/Saved attempts: 1/).waitFor();
    await page.locator('.activity-submission details summary').first().click();
    const request = JSON.parse(await page.getByLabel('Submission envelope for external review').inputValue());
    await page.getByRole('link', { name: 'Continue to written defense' }).click();
    await page.locator('[data-activity-id="defense"]').waitFor();
    await page.getByRole('button', { name: 'Save draft', exact: true }).waitFor();
    await page.getByLabel('Code, report or explanation', { exact: true }).fill('Half-up applies to each request; rounding the total loses billable cents.');
    await page.getByLabel('Environment used').fill('External reviewer claim');
    await page.getByRole('button', { name: 'Commit submission', exact: true }).click();
    await page.getByLabel('Reviewer-selected fresh prompt').fill('What changes for an empty file?');
    await page.getByLabel('Reviewer name or ID').fill('Practice reviewer');
    await page.getByLabel('Follow-up answer', { exact: true }).fill('The sum is zero cents.');
    await page.getByRole('button', { name: 'Commit follow-up before feedback' }).click();
    await page.getByText(/Saved attempts: 2/).waitFor();
    await visit('activity/lab');
    const { input, ...binding } = request;
    const definitions = JSON.parse(files['mastery/activities.json']).activities.find(a => a.id === 'lab');
    const result = { ...binding, status: 'complete', criteria: definitions.tests.flatMap(({ criteria, ...t }) => criteria.map(criterion => ({ ...t, criterion, outcome: 'pass' }))),
      provenance: { kind: 'public-test', reviewerId: 'local-public-tests', issuedAt: Date.now() } };
    await page.getByLabel('Result JSON', { exact: true }).fill(JSON.stringify(result));
    await page.getByRole('button', { name: 'Import provisional result' }).click();
    await page.getByRole('button', { name: 'Show saved rubric feedback' }).click();
    await page.getByText(/Provisional feedback \(public-test\)/).waitFor();
    await page.screenshot({ path: `/tmp/s12-lab-${width}.png`, fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await visit('calibration');
    const backupDownload = page.waitForEvent('download'); await page.locator('#cal-export').click();
    const backup = readFileSync(await (await backupDownload).path());
    const fresh = await browser.newContext({ viewport: { width, height: 950 } });
    try {
      await fresh.route('**/courses/demo.json', route => route.fulfill({ json: files }));
      const restored = await fresh.newPage(); restored.setDefaultTimeout(10000);
      await restored.goto(`${server.origin}/#/demo/calibration`);
      await restored.locator('.cal-foot input[type=file]').setInputFiles({ name: 'study-log.json', mimeType: 'application/json', buffer: backup });
      await restored.getByText(/Merged .* new answer/).waitFor();
      await restored.goto(`${server.origin}/#/demo/activity/lab`);
      await restored.getByText(/Provisional feedback \(public-test\)/).waitFor();
      await restored.getByText(/Saved attempts: 1/).waitFor();
      await restored.goto(`${server.origin}/#/demo/activity/defense`);
      await restored.getByText(/Saved attempts: 2/).waitFor();
      await restored.goto(`${server.origin}/#/demo/activity/delayed`);
      await restored.getByText('Independent evidence needed before delay starts', { exact: true }).waitFor();
      await restored.goto(`${server.origin}/#/demo/activity/future-audio`);
      await restored.getByText('This adapter is unavailable. This activity remains incomplete.', { exact: true }).waitFor();
      await restored.goto(`${server.origin}/#/demo/activity/future-trusted`);
      await restored.getByText('This adapter is unavailable. This activity remains incomplete.', { exact: true }).waitFor();
      await restored.goto(`${server.origin}/#/demo/activity/future-cloud`);
      await restored.getByText('Required environment unavailable', { exact: true }).waitFor();
      await restored.getByText(/Incomplete: required evidence remains/).waitFor();
      assert.equal(await restored.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    } finally { await fresh.close(); }
    assert.deepEqual(errors, []);
  } finally { await browser.close(); server.close(); }
});
